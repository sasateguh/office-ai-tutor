<?php

declare(strict_types=1);

/**
 * Jana fail EN bentuk TINDIH untuk latihan (src/Kandungan.php::benih) daripada versi EN PENUH + fail BM semasa:
 *   php alat/jana-tindih.php <subjek> <fail-en-penuh.php>
 * Menulis config/pek/<subjek>/en/latihan/<set>.php (satu fail setiap set, D74) = medan yang berbeza daripada BM sahaja
 * (termasuk accept/canonical/grid bila berbeza) + senarai en/latihan.php (susunan set = versi penuh), membuang fail set EN
 * yang tidak lagi disenaraikan, dan menyemak gabungannya SAMA TEPAT dengan versi penuh.
 * Aliran kerja biasa TIDAK memerlukan alat ini: sunting fail tindih EN terus (teks EN, dan grid/accept/canonical EN bila
 * soalan BM yang diubah menukar literal teks). Alat ini untuk menukar versi EN penuh kepada bentuk tindih.
 * Versi EN penuh semasa = php -r 'require "src/Kandungan.php"; var_export(Kandungan::benih("excel","latihan","en"));'
 */
require __DIR__ . '/../src/Kandungan.php';
[$_, $subjek, $failPenuh] = $argv + [null, null, null];
if (!$subjek || !is_file((string) $failPenuh)) {
    fwrite(STDERR, "guna: php alat/jana-tindih.php <subjek> <fail-en-penuh.php>\n");
    exit(2);
}
$ms = Kandungan::benih($subjek, 'latihan', 'ms');
$en = require $failPenuh;
$o = [];
foreach ($en as $sid => $s) {
    $set = [];
    foreach ($s as $k => $v) {
        if ($k !== 'questions' && ($ms[$sid][$k] ?? null) !== $v) {
            $set[$k] = $v;
        }
    }
    $bmIkutId = array_column($ms[$sid]['questions'] ?? [], null, 'id');
    foreach ($s['questions'] as $q) {
        $bm = $bmIkutId[$q['id']] ?? [];
        $b = [];
        foreach ($q as $k => $v) {
            if (($bm[$k] ?? null) !== $v) {
                $b[$k] = $v;
            }
        }
        if ($b) {
            $set['questions'][$q['id']] = $b;
        }
    }
    $o[$sid] = $set;
}
function ex(mixed $v, int $d = 1): string
{
    $p = str_repeat('    ', $d);
    if (!is_array($v)) {
        return var_export($v, true);
    }
    if (array_is_list($v)) {
        return '[' . implode(', ', array_map(fn($x) => ex($x, $d + 1), $v)) . ']';
    }
    $r = "[\n";
    foreach ($v as $k => $x) {
        $r .= $p . var_export($k, true) . ' => ' . ex($x, $d + 1) . ",\n";
    }
    return $r . str_repeat('    ', $d - 1) . ']';
}
$dir = __DIR__ . "/../config/pek/$subjek/en";
@mkdir("$dir/latihan", 0775, true);
$senarai = '';
foreach ($o as $sid => $set) {
    if (!preg_match('/^[a-z0-9_-]+$/', (string) $sid)) {
        fwrite(STDERR, "id set tidak sah: $sid\n");
        exit(2);
    }
    file_put_contents("$dir/latihan/$sid.php", "<?php\n\ndeclare(strict_types=1);\n\n/**\n * Practice (EN) set '$sid' — OVERRIDE form: only fields that differ from ../../latihan/$sid.php, merged by question id.\n * GENERATED by alat/jana-tindih.php; regenerate after editing the Malay file. Listed in ../latihan.php.\n */\nreturn " . ex($set) . ";\n");
    $senarai .= "    '$sid' => require __DIR__ . '/latihan/$sid.php',\n";
}
foreach (glob("$dir/latihan/*.php") ?: [] as $f) {
    if (!array_key_exists(basename($f, '.php'), $o)) {
        unlink($f);
    }
}
$keluar = "$dir/latihan.php";
file_put_contents($keluar, "<?php\n\ndeclare(strict_types=1);\n\n/**\n * Practice (EN) — OVERRIDE form (src/Kandungan.php::benih): only fields that differ from ../latihan.php, merged onto it by\n * question id. GENERATED by alat/jana-tindih.php from the full English version; regenerate after editing the Malay file.\n */\n// One set = one file latihan/<set>.php (D74); order here = order on the site. New set: add the BM + EN files and one line in each list.\nreturn [\n    '_tindih' => true,\n$senarai];\n");
$gabung = (function () use ($subjek) { return Kandungan::benih($subjek, 'latihan', 'en'); })();
echo $gabung === $en ? "SAMA TEPAT: $keluar + latihan/*.php\n" : "BERBEZA — semak\n";
exit($gabung === $en ? 0 : 1);
